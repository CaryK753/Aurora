import AppKit
func check(_ name: String, _ value: @autoclosure () -> Bool) {
    precondition(value(), name)
    print("✓ \(name)")
}
let board = NSPasteboard(name: .init("aurora-test-\(UUID().uuidString)"))
defer { board.releaseGlobally() }
let item = NSPasteboardItem()
item.setString("原文", forType: .string)
let rich = Data([0, 1, 2, 255])
item.setData(rich, forType: .rtf)
board.writeObjects([item])
let lease = SnippetPasteboard(board)
check("写入短语", lease.write("展开内容"))
lease.restore()
check("还原文字", board.string(forType: .string) == "原文")
check("保留富文本数据", board.data(forType: .rtf) == rich)
let concurrent = SnippetPasteboard(board)
check("第二次写入", concurrent.write("短语"))
board.clearContents()
board.setString("用户刚复制的新内容", forType: .string)
concurrent.restore()
check("不覆盖用户后续复制", board.string(forType: .string) == "用户刚复制的新内容")
board.clearContents()
let empty = SnippetPasteboard(board)
check("从空剪贴板展开", empty.write("短语"))
empty.restore()
check("恢复空剪贴板", board.pasteboardItems?.isEmpty != false)
check("统一域名大小写和结尾点", InputRuleDomain.normalize(" HTTPS://Example.COM./path ") == "example.com")
check("匹配子域", InputRuleDomain.matches(host: "sub.example.com", domain: "example.com"))
check("拒绝伪后缀域名", !InputRuleDomain.matches(host: "evilexample.com", domain: "example.com"))
check("拒绝通配符规则", InputRuleDomain.normalize("*.example.com") == nil)
check("拒绝空域名", InputRuleDomain.normalize(" ") == nil)
