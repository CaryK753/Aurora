import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case system, zhHans, en
    var id: String { rawValue }
    var label: String {
        switch self {
        case .system: return "跟随系统"
        case .zhHans: return "简体中文"
        case .en: return "English"
        }
    }
}

